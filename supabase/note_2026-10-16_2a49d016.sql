- 跟踪清单：① 是否通过董事会/股东会审议并披露正式方案；② 是否完成首次实施并公告；③ 月度进展公告中累计金额占方案下限的比例；④ 用途是否由激励变更为注销。

【个人观点】
- 本轮回购整体规模偏小，对市场信心恢复的拉动有限，性质上更像对监管指导意见的回应，而非基于自身价值判断的主动出手。
- 回购存在实施周期，公告语气与实际出金节奏可能明显背离，真正需要跟踪的是企业执行的力度，而非披露的家数。
- 参照案例：宁德时代为 200–400 亿元级方案且全部用于注销，属超大额回购，实际购买节奏偏慢——大额方案的落地周期更长，不宜按公告金额线性外推。（宁德进度数据待补充核实）

【结构性特征】注销式占比升至过半，但本批仍以激励式为主
