【判断三】实施端才是关键变量，提议 ≠ 落地，需按企业逐一跟踪执行力度
- 执行慢的样本：中泰证券方案规模 1–2 亿元、9-9 起算，至 10-15 累计仅 3832.87 万元，为方案下限的 38.33%，四个月进度不足四成。
