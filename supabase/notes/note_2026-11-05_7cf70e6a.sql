一、标准：空间 = 市场规模 × 国产缺口 × 时间窗

WSTS 6 月把 2026 全球半导体从 9,754 亿美元上调到 1.51 万亿美元，几乎全部来自存储（+250%）。基准变了：过去在固定总量里抢份额，现在多了总量膨胀这一项。

排序：
1）先进封装 560–580 亿美元，高端国产化 <10%、混合键合 <5%，+30%——全链唯一量、价、国产化率同时有利
2）HBM 工艺链 546 亿美元，国产化 ≈0，+58%——本体做不出来（长鑫 HBM3E 良率约 21%），只能投工艺链
3）光互连上游 260 亿美元、光芯片 <20%、+60%——模块端已饱和，机会在光源与光引擎
4）量检测 130 亿美元、<10%、+25%——纯替代，市场小

不看好：成熟制程代工、功率与 SiC、消费 MCU、硅片（有量无质）。

存储本体更正：长鑫 2026-07-27 已上科创板（688825），现市值 2.89 万亿、PE 20.7 倍。不投不是进不去，是已按周期顶部利润定价。

共同变量只有 2027 年产能：CoWoS 3.5 万 → 12–14 万片/月，长鑫 27 万 → 2028 年 44.7 万片。订单在产能落地前已签完，窗口是现在到 2027 上半年。

二、卡点不在技术，在“齐套”

2026 全球封测 961 亿美元、先进封装 522 亿首次过半，但 AI 封装毛利 48%–55%、传统封装 13%–17%——不是一个行业，是两个行业共用一套设备。台积电 CoWoS 占 2.5D/3D >85%；大陆五家合计约 34%，高端不足 10%。

1）客户结构最硬：台积电 3nm 需求中云端 AI 占比 2026 年 35%→2027 年 72%，芯片先拿到晶圆才能进 CoWoS。OSAT 只拿外溢与第二供应源，天花板不在技术，在客户结构。
2）物料齐套是新增变量：盛合晶微 Q3 营收 -8.33%、归母 -45.96%，财报写“上游核心物料（HBM、TSV 转接板）供给紧张”，同期存货升到 17.23 亿、固定资产增到 121.72 亿——在扩产但买不到东西。瓶颈从“会不会做”变成“齐不齐套”。
3）国产化率矩阵：2.5D/3D 高端 <10%（技术差得小、产能差 10 倍）、混合键合设备 <5%、ABF 载板 4%、Underfill ≈0。涨价佐证：引线框架 +15%–30%、CoWoS 拟涨 10%–20%。

三、物料四层：价值量与国产化率同时差 10 倍

L1 基板（占成本 70%–80%、国产 4%）：深南电路是大陆唯一稳定量产 22 层内 FC-BGA ABF（H1 封装基板 36.67 亿、+110.76%）；兴森科技良率 90%+、长鑫 DDR5 FCBGA 份额 15%–20%。上游膜味之素 95%+，5 月涨 30%、8 月对大陆砍供 30%——全链唯一“断供即停摆”的点。

L2 包封填充（高端 EMC 10%–20%、Underfill ≈0）：华海诚科前三季 7.63 亿（+173%）；联瑞新材球硅国内 50%+、唯一供 HBM 用 Low-α。L3 工艺化学品（国产 5%–30%）：安集 CMP 抛光液全球 13%、前三季扣非 7.3 亿；鼎龙 PSPI 全球第二家量产。L4 上游原料：Low CTE 玻纤布交期 16–20 周，电子级树脂与 ABF 膜本体基本空白。

国产膜梯队：华正 CBF（300 万㎡ 满产、良率 85%–88%、昇腾份额 20%→30%）> 纽菲斯（92%）> 宏昌 > 生益、天和、激智。差距就两个数字：良率 85–88% 对 99%；20 层已认证、HBM 超高阶无量产。

反直觉：台积电 CoPoS 首代（2029H1）锁定 ABF 有机方案，玻璃被踢出首代——不是替代，是“ABF 包玻璃芯”。ABF 需求 2025–2028 年 CAGR 22%、供给 12%，2027 年起供不应求，景气比预期长 2–3 年。

四、核心企业：华正新材（603186）

定性：覆铜板周期股，CBF 是期权。前三季覆铜板占营收 85%；CBF 最乐观只贡献 2–3 亿收入、3,000–5,000 万净利，而净利 8 亿——期权占比不到 5%。

业绩：2023–2024 连亏，2025 归母 2.77 亿（扣非 0.66 亿）→ 2026 前三季 56.10 亿（+75.5%）、归母 8.00 亿（+1,178%）、扣非 7.93 亿（+1,499%）。Q1 0.31 → Q2 1.42（毛利 18.72%）→ Q3 6.27 亿（毛利 36.06%）。

利润来源（最关键）：Q3 毛利增量 6.33 亿中，收入增量贡献 1.73 亿、毛利率提升贡献 4.60 亿，是量增的 2.7 倍。产能没加（360 万张/月设计、实出 260–280 万张满产），钱是提价来的。

36% 里结构占多少：高端占比 9–10%→20%→全年 30%，但连 FR-4 都能做 40% 毛利，管理层自己说“成熟 CCL 常态 15%–20%，希望长期保持 25% 以上”。当前是全品类缺货，不是结构溢价。结构是慢变量，36% 是快变量。

估值三层矛盾：市值 232 亿；PE(TTM) 22.9 倍；Q3 年化 9.2 倍；天风乐观 500 亿（2027 高端 13 亿×20 + FR4 12 亿×10），而 FR4 那 12 亿不成立——2025 年扣非只有 0.66 亿。

财务：资产负债率 63.97%、速动 0.95；Q3 单季经营现金流 1.82 亿对净利 6.27 亿，现金含量 29%——这才是 12 亿定增的真实动因。2027 年珠海只放 50 万张/月，真实量增约 15%。

CBF 分歧本身是信息：2026 收入 2.2–2.8 亿对 4.5–7 亿，差 2 倍，说明出货量从未被公开数据验证。该盯的是“与安捷利美维合作的存储 FCBGA 样品完成 3 轮可靠性测试、推进长存/长鑫认证”，不是昇腾。

结论：定价矛盾在周期顶利润 × 成长股估值，先决定买哪一个；最重要的指标不是利润，是 Q4 毛利率能否守住 35%（守住=结构成立，掉到 30% 以下=缺口溢价）；风险不在技术，在 2028 年供给——四家合计扩产 1.17 亿㎡。

