一、唯一真强项：DDIC 高压工艺的规模经济

DDIC 高压工艺投片份额 32%（2026H1，去年同期 30%），DDIC 代工按营收 23.3% 第一，台积电 22.8%、联电 13.5%；全球晶圆代工整体第九、大陆第三；CIS 代工全球第五、大陆第三。

这个第一不是自己抢来的，是订单转移送来的。上半年大陆晶圆厂 DDIC 份额从 52% 升到 56%，台湾 34%、韩国 9%；三星、力积电、台积电主动收缩 HV 业务，份额都掉到 5%，让出的订单主要流向晶合与粤芯（5%→7%）。

