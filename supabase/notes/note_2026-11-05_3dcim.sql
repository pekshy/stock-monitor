update research_notes set hash='d89bd8f550b79732251d022417692006a4087714', title='3D 存算一体：技术路线与企业分布', body='一、先分清三件被混称为「3D 存算一体」的事
1、3D 封装近存（PNM）：计算全部留在逻辑晶圆，存储晶圆只负责供带宽。本质是带宽工程——靠混合键合把存储层叠上来，把访存带宽从 HBM 的 TB/s 级推到 10 TB/s 级。
2、3D 堆叠存内（CIM）：计算发生在存储阵列内部，堆叠是为了扩容量而不掉带宽。本质是容量工程——单层 SRAM 阵列只有 MB 级，只能靠叠层把模型装进去。
3、HBF / 高带宽闪存：NAND 堆叠 + 近存计算，卡在 HBM（贵、容量小）与 SSD（便宜、带宽低）之间。本质是成本工程。
>> 三者共用混合键合工艺，但设计目标、瓶颈、客户完全不同。把它们当成一条路线，是当前最常见的误读。

二、按介质分四条路线
· SRAM-CIM：能效最高（pJ 级）、容量最小（MB 级）、CMOS 兼容、可叠层扩容，端侧首选。代表：知存科技（WTM2101 已在 TWS 与安防规模出货）、九天睿芯（ADA100 20μW 已量产出货）、苹芯科技；恒烁股份走 NOR Flash 路线，严格说属 Flash-CIM。
· DRAM-CIM / 近存：容量 GB 级、带宽高、成本居中，面向云端与边缘推理。代表：算苗科技（A4E，8 层存储晶圆堆叠、16TB/s）、三星 HBM-PIM、SK 海力士 AiMX（GDDR6-AiM）。
· NAND / HBF：容量 TB 级、成本最低，但写入寿命与随机读差。代表：九天睿芯（SRAM + HBF 三维融合）、思敏威（与领开半导体合作 HBF+）、SanDisk 与 SK 海力士（2026 年发布首份 HBF OCP 规范）。
· 新型非易失（ReRAM / MRAM / PCM）：能效极致，但模拟精度与工艺成熟度是硬伤。代表：亿铸科技、昕原半导体（ReRAM）、Mythic（Flash 模拟 CIM）。
>> 介质决定一切：容量差三个数量级，能效差两个数量级。所谓路线之争，本质是「要装多大的模型、能忍多少延迟」。

三、堆叠工艺才是真分水岭
· 混合键合（Hybrid Bonding）：Cu-Cu 直接键合，间距可做到 10μm 以下，互连密度比微凸点高约两个数量级。算苗 A4E 的 8 层堆叠靠的就是这条工艺。
· TSV + 微凸点：HBM 的现行方案，成熟但密度低、成本高，TSV 占面积、挡布线。
· 单片 3D（Monolithic）：上层器件低温直接长在下层，密度最高，仍处研发阶段（CEA-Leti、IMEC）。
>> 判断标准很硬：谁能把键合间距做到 10μm 以下并守住良率，谁才有资格谈 3D。这一层决定成本，成本决定能否商用。

四、三个真瓶颈，都不在算力
1、热：计算与存储叠在一起，功耗密度翻倍，中间层没有散热路径。SRAM-CIM 单层能效好，一叠层就撞热墙。
2、良率：晶圆对晶圆键合，任一层失效则整 stack 报废，KGD（已知合格 Die）测试能力是核心。
3、工具链：编译器要把模型映射到物理阵列，还要处理多层存储的地址空间，没有成熟 EDA。这是所有 CIM 公司共同的短板。
>> 因此「能效提升 10 倍」通常是单个 macro 的实测值，不是整芯片，更不是整机。

五、企业分布与所处阶段
· 已量产出货：知存科技（WTM2101）、九天睿芯（ADA100，20μW）
· 已流片待量产：算苗科技（A4E，2026-06 流片，8 层堆叠 / 16TB/s，2027 年规模量产）、九天睿芯（二代 13B 已流片）、微纳核芯（三款投片，2027 年初送测）
· 已投产 / 在研：后摩智能（A20 3D CIM 已投产，M6X 在研；M50 为 2D 数字 CIM，已拿 150+ 定点）
· 天使 / 早期：思敏威（3D-cHMC 基座，FP4 存内计算 IP 已验证）
· 海外：三星 HBM-PIM、SK 海力士 AiMX、d-Matrix（数字 CIM + 3D 封装）、Mythic、Axelera AI

六、验证一条路线是否成立，看三个硬指标
1、键合层数与间距——层数决定带宽上限，间距决定互连密度，两个数都要报。
2、整芯片能效（TOPS/W），不是 macro 能效——差一个量级很常见。
3、客户是否重复下单——定点与送测都是过程指标，复购才是路线被验证的信号。
