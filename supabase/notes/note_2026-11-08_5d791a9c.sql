长晶炉国产化最彻底（晶盛机电、晶升股份），单台价格从 300 万元压到 150 万元以内；但切割研磨被迪思科垄断约 70%，高温离子注入与检测设备仍依赖进口，关键制程进口设备覆盖率超过 60%。

