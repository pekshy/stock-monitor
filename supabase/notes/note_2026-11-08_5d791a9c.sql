四、三个容易读错的数字

第一，「国产化率 40%」是全球份额，不是国内自给率。中国是最大需求市场，衬底自给率实际高于这个数；但高端导电型、车规级仍要靠进口补，看到 40% 就以为国产化完成是误读。

第二，8 英寸良率的 50%、70%、85% 分属三个口径：国内综合、国内头部、海外龙头。车规级良率差 11 个百分点才是最该盯的指标，不是综合良率。

第三，价格跌幅比国产化率更能说明问题。8 英寸三年跌 79%、6 英寸跌破成本线，说明门槛消失的速度远快于份额提升的速度——这对衬底厂是坏消息，对器件厂是好消息。

