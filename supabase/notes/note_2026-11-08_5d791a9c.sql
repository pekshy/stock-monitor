二、四段门槛拆解

（1）6 英寸衬底：已踏平。

PVT 法长晶，2000–2500℃，生长速率 0.1–0.3mm/h，一炉 7–14 天，技术难在微管密度与 TSD 位错控制。但十年工艺积累把它变成了「会做就能做」。2026 年国内 6 英寸报价 200–300 美元/片，部分企业低于成本线出货，较 2023–2024 年峰值回落约 70%。中国厂商占全球导电型衬底 40% 以上份额，天岳先进 2025 年以 27.6% 居全球第一、销量 63.33 万片（+75.33%）。这一段的竞争已经是成本战，不是技术战。

（2）8 英寸衬底：真门槛。

难的不是「长出来」，是「长好」：热应力导致翘曲（BOW/WARP）、位错增殖、金刚线切割损耗 30%–40%、表面平整度。国内综合良率 50%–70%，海外头部 85%，车规级相差约 11 个百分点。价格上，8 英寸单价从 2023 年 29417 元/片跌到 2025 年 6172 元/片（天科合达招股书，-79%），2026 年止跌企稳——因为 8 英寸有效供给仍有约 14 万片缺口，结构性短缺取代了全面过剩。经济账很清楚：单片可用 die 从 448 颗增至 845 颗（+89%），单位成本降 20%–35%，这是所有厂商必须跳 8 英寸的理由。

（3）车规 MOSFET：最高。

沟槽栅是英飞凌的专利地盘，国内多数还在平面栅；栅氧界面态导致 Vth 漂移与 BTI 退化，要过 AEC-Q101 与千小时高温反偏。全球前五（意法、英飞凌、Wolfspeed、罗姆、安森美）合计 72.5%，中高压 SiC MOSFET 国内自给率不足 28%。二极管已经打到白菜价，MOSFET 还没有——这是整条链上唯一「量价都还没被中国厂商改写」的环节。

