  $note$【一、五条结论】

1）2026 全年国产 AI 加速卡 220–260 万张（窄口径，云侧训练+推理卡），同比约 +40%；若计入信创整机内置卡、白牌与边缘推理卡，宽口径可到 300 万张以上。同期英伟达在华约 200 万张（上半年 67.8 万、同比 −44%），国产份额首次过半，落在 55–62%。

