【六、判断】

① 2026 是"分母年"：国产总量从 165 万冲到 220–260 万，增量主要来自推理卡与非 GPU 加速器（H1 非 GPU 101.6 万首次超 GPU 99.1 万），不是训练卡替换。
② 头部集中度缓降是健康信号：45% 的昇腾 + 35% 的二线 + 20% 长尾，比 2025 年"一家一半"更接近可持续结构。
③ 通用 GPU 的排序已定：摩尔 > 沐曦 > 燧原 > 天数 > 壁仞，按卡数和营收两个维度都成立；这个排序 2027 年之前不会变，因为变的前提是 CoWoS 配额重新分配。
④ 指引与兑现的缺口是本板块最大的 alpha 来源：凡是给出"营收 3 倍增长 + 卡数 3 倍增长"双指引的公司，至少有一个是假的，用均价一除就能看出来。
⑤ 不要把 2027 数字折回 2026 估值：240–260 万张的昇腾需要 HBM3 供给同比 +130%，而长鑫 HBM3 2026 年底才小批量试产，这是硬约束。

