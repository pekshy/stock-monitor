  $note$【一、四条结论】

1）FC-BGA 是封装形式，ABF 是做它的关键材料；玻璃基板替代的是"芯板"，ABF 增层仍要用——不是绕开味之素。
2）瓶颈从 CoWoS 转向基板：CoWoS 缺口 2026 年底收窄至 10%，ABF 基板 2027 年缺口 22%、2028 年 29%–51%，2027 年最缺。
3）扩产不等于产能释放：转产 AI 良率从 80% 掉到 50%–60%，24 层占用产能是 16 层的 1.5 倍，菲律宾 18 万㎡ 明确不做 AI。名义增 30%–40%，实际有效产出只增 15%–20%，而需求增速 60%–70%。
4）国产化是"从 0 到 1"：深南 22 层及以下量产、月 1.5 万㎡；兴森小批量且高端 FC-BGA 毛利率为负；两家合计不足全球有效产能 3%。

【二、结构】

FC-BGA = Flip Chip（倒装）+ BGA（焊球阵列），核心是中间的基板。基板干四件事：扇出（40μm 凸点→800μm 焊球，差 20 倍）、供电（上千安、几十层铜）、信号完整性（HBM/224G SerDes）、缓冲硅与 PCB 的热膨胀差。

ABF（味之素堆积膜）是积层绝缘膜：10/10μm 线宽（头部试 5/5）、支撑 20 层以上、可激光打 30–50μm 微孔。味之素占全球 95%+，2026Q3 涨价约 30%，新厂 2032 年才投产——这是全行业扩产的真实上限。

量级：AI 加速卡基板 85×85mm、20 层以上、均价约 68.5 美元/颗；EMIB-T 约 200 美元、AMD MI450 约 340 美元。

【三、供需】

需求：2026 年服务器用 FC-BGA 61.2 亿美元、占 43%，首次超过手机；>20 层大尺寸基板 1.28 亿颗（+43.6%）。关键指标是单颗占产能——Ibiden SAP 负荷 2024 年 1.0 → 2026 年 1.8 → 2027 年 2.5。

供给三约束：味之素膜（95%、2032 年前无大产能）、T-glass 玻纤布（日东纺，短缺至 2028）、扩产周期 18–24 个月。

价格信号：六大厂 2026 年产能全部预定，交期从 6–8 个月拉到 12–14 个月，客户预付最高 50% 产能款，长约签到 2028 年。

【四、格局】

16 层折算月产能：欣兴约 20 万㎡（有效 15 万）、Ibiden 约 12 万㎡（曝光机口径 50 万、AI 相关 24 万）、三星电机 12 万、南亚 10 万、AT&S 10 万、景硕 8 万、Shinko 5 万；全球 77 万㎡ 理论、65–70 万有效。

份额有三套口径：高端 FC-BGA 为 Ibiden 35%/Shinko 18%/欣兴 14%/AT&S 10%/南亚 5%；ABF 载板为欣兴 24%/南亚 20%/Ibiden 20%；整体 CR5 约 82%。差异来自"高端"是否限 20 层以上。

客户绑定比份额重要：英伟达 Ibiden 65%+、欣兴 30%；谷歌 TPU 欣兴 30%+、三星 30%、南亚 25%–30%；AMD MI450 由 Ibiden 主供。

全行业扩产投资超 70 亿美元，有效产能 2028–2029 释放。注意：日系龙头对核心客户难涨价（物料由客户指定），受益者更多是二线厂与材料商。

【五、国产化】

第一梯队：深南电路——22 层及以下量产、24 层打样；广州月 1.5 万㎡ 爬坡；封装基板占营收 24%；已导入国内 CPU/GPU 客户。

第二梯队：兴森科技——华为为核心客户、昇腾占其 ABF 产能 50%+，另服务平头哥/沐曦/天数智芯/新华三/飞腾；2026H1 基板收入 12 亿元（+67%），但高端 FC-BGA 毛利率为负；72 亿元扩产、新增 2.6 万㎡/月。礼鼎（鹏鼎参股 13.72%）已规模化量产 ABF 载板。芯爱科技（未上市）A2 轮 15 亿元、累计超 50 亿元，已过日月光/矽品认证。

第三梯队：沪电股份（中低层认证）、胜宏科技（技术储备）、珠海越亚（coreless）。

三道门槛：层数（14 层以下良率 95%+、16–20 层约 90%、24 层以上仅打样）、良率（昇腾大尺寸型号差 10pct+）、材料（ABF 膜 100% 进口）。

材料端：华正新材 CBF 膜小批量、南亚新材参股兴南创芯 20%、生益科技做基材、方邦股份可剥铜、宏和/中材/光远做电子布。

【六、玻璃基板】

认知：换掉的是有机芯板，TGV 负责互连，ABF 增层保留——不是取代整块载板。

海外：Intel 2026-01 展示玻璃芯 Xeon 6+，但属自家专线、不对外卖基板，240×240mm 面板翘曲严重；Absolics 向 AMD 送 MI400 样品、与亚马逊评估线 9 月无限期推迟，2026 年底完成量产准备；三星 GlaSSEM 2027H2 建供货体系，因可靠性问题（高低温/湿热形变、微孔导通不稳）或推至 2028 后；台积电 CoPoS 2026 验证、2027 试产、2028H2 量产，良率"还要一年"；DNP 2028 建线、2030 量产；LG Innotek 2028。

NVIDIA 9 月底被曝评估玻璃基板，联合 SCHMID 开发设备，要求日韩厂 2 年内完成、最快 2028 落地；SCHMID 承认 TGV 金属化是最大卡点。

国内：京东方最前——试验线全流程贯通，24 层 11-2-11、>100×100mm 送样，过六项可靠性测试（Pre-con/TCB 1000/UHAST/BHAST/HTSL/LTSL），已做整机实测；产能 1000 片/月，2027Q1–Q2 做量产决策（前提是客户与良率），目前未量产未创收。蓝思 22 层、韩国客户验证通过、北美测试中、年底投产。TCL 2026H2 出样。沃格 10 万㎡/年、孔径 3μm/深宽比 150:1/良率 90%+、已供中际旭创 1.6T，但未规模化销售。佛智芯 5000 片/月。

设备与材料先于基板收入：帝尔激光（改质设备订单+复购）、东威科技（电镀）、天承科技（填孔化学品）、北方华创/汇成真空（PVD）、盛美/芯碁（面板设备）、日联（检测）、蓝特（玻璃晶圆）。

卡点：TGV 成孔已过验证，金属化填铜是最大瓶颈；良率 Absolics 65%、行业初期 75%–85%、成熟 ABF 90%–95%；成本 3–5 倍，2030 年降 40%–60%。

