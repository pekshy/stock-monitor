def inject_data_ts() -> None:
    p = os.path.join(ROOT, "src", "research", "data.ts")
    src = io.open(p, encoding="utf-8").read()

    # 1) TREE 细分：按 (seg, name) 顺序游标推进，在 desc 行后插入 detail 行
    start = src.index("export const TREE")
    brace = src.index("{", src.index("=", start))
    depth = 0
    for i in range(brace, len(src)):
        if src[i] == "{":
            depth += 1
        elif src[i] == "}":
            depth -= 1
            if depth == 0:
                end = i + 1
                break
    body = src[brace:end]
    cursor = 0
    for seg_id, name, text in SUB_DETAILS:
        key = '"name": "%s"' % name
        pos = body.index(key, cursor)
        s = body.index('"desc":', pos)
        line_end = body.index("\n", s)
        indent = ""
        for ch in reversed(body[:s]):
            if ch == "\n":
                break
            indent = ch + indent
        insert = '\n%s"detail": "%s",' % (indent, text)
        body = body[:line_end] + insert + body[line_end:]
        cursor = line_end + len(insert)
    src = src[:brace] + body + src[end:]

    # 2) 行业级：INDUSTRY_DATA 内 industry 对象的 name 行后插入 detail
    start = src.index("export const INDUSTRY_DATA")
    brace = src.index("{", src.index("=", start))
    depth = 0
    for i in range(brace, len(src)):
        if src[i] == "{":
            depth += 1
        elif src[i] == "}":
            depth -= 1
            if depth == 0:
                end = i + 1
                break
    body = src[brace:end]
    for ind_id, text in INDUSTRY_DETAILS.items():
        key = '"%s": {' % ind_id
        pos = body.index(key)
        s = body.index('"name":', pos)
        line_end = body.index("\n", s)
        indent = ""
        for ch in reversed(body[:s]):
            if ch == "\n":
                break
            indent = ch + indent
        insert = '\n%s"detail": "%s",' % (indent, text)
        body = body[:line_end] + insert + body[line_end:]
    io.open(p, "w", encoding="utf-8", newline="").write(src[:brace] + body + src[end:])
    print("data.ts: %d subs + %d industries" % (len(SUB_DETAILS), len(INDUSTRY_DETAILS)))


def inject_demo() -> None:
    p = os.path.normpath(os.path.join(ROOT, "..", "demo", "index.html"))
    src = io.open(p, encoding="utf-8").read()

    # 1) SUBS 细分：desc:'...' 后同行插入 detail:'...'
    for seg_id, name, text in SUB_DETAILS:
        key = "name:'%s'" % name
        pos = src.index(key)
        ds = src.index("desc:'", pos)
        de = src.index("',", ds)  # desc 值的收尾
        assert de != -1
        insert = "',detail:'%s'" % text
        src = src[:de] + insert + src[de + 1:]
    # 2) DATA 行业：name:'...' 行后插 detail
    for ind_id, text in INDUSTRY_DETAILS.items():
        key = "%s: {" % ind_id
        pos = src.index(key)
        s = src.index("name:'", pos)
        ne = src.index("',", s)
        insert = "',\n    detail:'%s'" % text
        src = src[:ne] + insert + src[ne + 1:]
    io.open(p, "w", encoding="utf-8", newline="").write(src)
    print("demo/index.html: %d subs + %d industries" % (len(SUB_DETAILS), len(INDUSTRY_DETAILS)))


